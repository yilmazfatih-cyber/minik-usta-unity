#!/usr/bin/env python3
"""Generates Assets/MinikUsta/Presentation.Core/Ui/FontMetrics.cs from the shipped Baloo 2 ExtraBold TTF (paket V1).

The advance width of every mapped code point (font units, unitsPerEm 1000) so text can be fitted to its rectangle the same
way in Unity (uGUI Text at a fixed size, no best fit) and in tools/art/compose.mjs. Kerning is ignored (a few px at most).
Usage: python3 -I tools/font/gen-metrics.py   (needs fontTools; FontMetricsTests checks the table against the TTF)
"""
import os
import sys
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TTF = os.path.join(ROOT, 'Assets', 'MinikUsta', 'Resources', 'fonts', 'Baloo2-ExtraBold.ttf')
OUT = os.path.join(ROOT, 'Assets', 'MinikUsta', 'Presentation.Core', 'Ui', 'FontMetrics.cs')

f = TTFont(TTF)
upm = f['head'].unitsPerEm
cmap = f.getBestCmap()
hmtx = f['hmtx']
hhea = f['hhea']
pairs = sorted((cp, hmtx[g][0]) for cp, g in cmap.items())
lines = []
row = []
for cp, adv in pairs:
    row.append('{0x%X, %d}' % (cp, adv))
    if len(row) == 8:
        lines.append('            ' + ', '.join(row) + ',')
        row = []
if row:
    lines.append('            ' + ', '.join(row) + ',')
src = '''#nullable enable
// GENERATED by tools/font/gen-metrics.py from Resources/fonts/Baloo2-ExtraBold.ttf — do not edit by hand (paket V1).
// Advance widths (font units, %(upm)d per em) of every code point the font maps; FontMetricsTests checks them against the TTF.
using System.Collections.Generic;

namespace MinikUsta.Presentation.Ui
{
    public static partial class FontMetrics
    {
        public const int UnitsPerEm = %(upm)d;
        /// <summary>hhea ascender / descender (font units): uGUI's line box is their sum.</summary>
        public const int Ascender = %(asc)d;
        public const int Descender = %(desc)d;

        private static readonly Dictionary<int, int> Advances = new Dictionary<int, int>
        {
%(rows)s
        };
    }
}
''' % {'upm': upm, 'asc': hhea.ascent, 'desc': hhea.descent, 'rows': '\n'.join(lines)}
with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(src)
print('wrote', OUT, len(pairs), 'code points')
