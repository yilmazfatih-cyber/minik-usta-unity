#!/usr/bin/env node
/**
 * Writes Assets/MinikUsta/Resources/audio/sounds.json from the web repo's design tokens (src/theme/tokens.json `audio`, the
 * source of truth: ZzFX recipes `sfx.<name>` = one call, `seq.<name>` = `[startMs, params]` steps; paket V2, decision D-057).
 *
 * The one deliberate change is `sampleRateHz`: the web build renders 22 050 Hz (small buffers for a browser tab); the Unity
 * AudioClip is created at 44 100 Hz (the rate every mixer runs at, no resampling on the device). The recipes are rate
 * independent (every time and frequency is in seconds / Hz), so the sounds are the same; `--rate N` overrides.
 *
 * Usage: node tools/audio/gen-sounds.mjs [/path/to/minik-usta] [--rate 44100]   (node 22; no packages)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const args = process.argv.slice(2);
const rateAt = args.indexOf('--rate');
const rate = rateAt >= 0 ? Number(args[rateAt + 1]) : 44100;
const WEB = resolve(args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--rate') ?? join(ROOT, '..', 'minik-usta'));
const tokens = JSON.parse(readFileSync(join(WEB, 'src', 'theme', 'tokens.json'), 'utf8'));
const a = tokens.audio;
if (!a || !a.sfx || !a.seq) throw new Error('tokens.json has no audio.sfx / audio.seq');
const names = (o) => Object.keys(o).filter((k) => !k.startsWith('_doc'));
const both = names(a.sfx).filter((k) => k in a.seq);
if (both.length) throw new Error(`names in both audio.sfx and audio.seq: ${both.join(', ')}`);

const num = (n) => String(Math.round(n * 1e6) / 1e6);
const params = (p) => '[' + p.map(num).join(', ') + ']';
const lines = [];
lines.push('{');
lines.push('  "_doc": "GENERATED by tools/audio/gen-sounds.mjs from the web design tokens (audio.*): do not edit by hand. sampleRateHz is 44100 here (the web build renders 22050); recipes are rate independent. sfx.<name> = one ZzFX call [volume, randomness, frequency, attack, sustain, release, shape, shapeCurve, slide, deltaSlide, pitchJump, pitchJumpTime, repeatTime, noise, modulation, bitCrush, delay, sustainVolume, decay, tremolo, filter]; seq.<name> = [[startMs, params], ...] mixed into one buffer (peak <= 1).",');
lines.push(`  "sampleRateHz": ${rate},`);
lines.push(`  "comboRootHz": ${num(a.comboRootHz)},`);
lines.push(`  "comboSemitones": [${a.comboSemitones.join(', ')}],`);
lines.push(`  "sameSoundCooldownMs": ${num(a.sameSoundCooldownMs)},`);
lines.push(`  "maxVoices": ${a.maxVoices},`);
lines.push('  "sfx": {');
names(a.sfx).forEach((k, i, all) => lines.push(`    "${k}": ${params(a.sfx[k])}${i < all.length - 1 ? ',' : ''}`));
lines.push('  },');
lines.push('  "seq": {');
names(a.seq).forEach((k, i, all) => {
  lines.push(`    "${k}": [`);
  a.seq[k].forEach(([ms, p], j, steps) => lines.push(`      [${num(ms)}, ${params(p)}]${j < steps.length - 1 ? ',' : ''}`));
  lines.push(`    ]${i < all.length - 1 ? ',' : ''}`);
});
lines.push('  }');
lines.push('}');
const out = join(ROOT, 'Assets', 'MinikUsta', 'Resources', 'audio', 'sounds.json');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
// round trip: the file must hold exactly the recipes of the tokens
const back = JSON.parse(readFileSync(out, 'utf8'));
const same = (x, y) => JSON.stringify(x) === JSON.stringify(y);
for (const k of names(a.sfx)) if (!same(back.sfx[k].map(Number), a.sfx[k].map((v) => Math.round(v * 1e6) / 1e6))) throw new Error(`sfx ${k} changed while writing`);
console.log(`audio: ${names(a.sfx).length} sfx + ${names(a.seq).length} seq at ${rate} Hz -> ${out}`);
