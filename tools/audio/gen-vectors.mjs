#!/usr/bin/env node
/**
 * Bit-parity vectors of the C# ZzFX port (Presentation.Core/Audio/ZzFx.cs, SoundBank.cs) against the web synthesizer
 * (src/services/audio.ts `renderSound`, the source of truth): for every sound of the design tokens, the sample count, the
 * peak, the sum of |sample|, an FNV-1a 32 hash of the int16-quantised buffer and a list of sample points (first 8, last 8
 * and about 64 evenly spread ones). The C# test renders the same sounds from Resources/audio/sounds.json and compares:
 * the count exactly, the points within 1e-5, the hash for sounds whose quantisation cannot flip (see `chaotic`).
 *
 * `chaotic` = a recipe containing a noise step (shape 4, `sin(t**3)`): there one ulp of `t**3` (libm pow differs from V8's) can move
 * late samples, so those sounds get a looser point tolerance (measured worst: 7e-6 on sfx_fall) and no hash check.
 *
 * Output: Assets/MinikUsta/Presentation.Core.Tests/Golden/audio_vectors.json
 * Usage: node tools/audio/gen-vectors.mjs [/path/to/minik-usta]   (node 22 type stripping; no packages)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const WEB = resolve(process.argv.slice(2).find((a) => !a.startsWith('--')) ?? join(ROOT, '..', 'minik-usta'));
const audio = await import(pathToFileURL(join(WEB, 'src', 'services', 'audio.ts')).href);
const { TOKENS } = await import(pathToFileURL(join(WEB, 'src', 'theme', 'tokens.ts')).href);

const fnv32 = (samples) => {
  let h = 0x811c9dc5;
  for (const s of samples) {
    const q = Math.round(Math.max(-1, Math.min(1, s)) * 32767);
    const v = q & 0xffff;
    for (const byte of [v & 0xff, v >> 8]) {
      h ^= byte;
      h = Math.imul(h, 0x01000193) >>> 0;
    }
  }
  return h.toString(16).padStart(8, '0');
};
const hasNoise = (name) => {
  const r = audio.resolveSound(name);
  const steps = r.kind === 'sfx' ? [r.params] : r.steps.map(([, p]) => p);
  return steps.some((p) => p[6] === 4);
};
const pointsOf = (s) => {
  const idx = new Set();
  for (let i = 0; i < Math.min(8, s.length); i++) idx.add(i);
  for (let i = Math.max(0, s.length - 8); i < s.length; i++) idx.add(i);
  const stride = Math.max(1, Math.floor(s.length / 64));
  for (let i = 0; i < s.length; i += stride) idx.add(i);
  return [...idx].sort((a, b) => a - b).map((i) => [i, s[i]]);
};
const entry = (name, rate) => {
  const s = audio.renderSound(name, TOKENS.audio, rate);
  let peak = 0;
  let sumAbs = 0;
  for (const v of s) {
    peak = Math.max(peak, Math.abs(v));
    sumAbs += Math.abs(v);
  }
  const chaotic = hasNoise(name);
  return { name, rate, length: s.length, peak, sumAbs, hash: fnv32(s), chaotic, points: pointsOf(s) };
};

const names = audio.soundNames();
const out = {
  _doc: 'GENERATED by tools/audio/gen-vectors.mjs from the web synthesizer; see the tool header for the fields.',
  webAudioRate: TOKENS.audio.sampleRateHz,
  sounds: [
    ...names.map((n) => entry(n, 44100)),
    // the web rate: the same recipes at 22 050 Hz (proves the rate is a parameter, not baked in)
    ...['sfx_pick', 'sfx_blocked', 'sfx_place_bad', 'sfx_coin', 'sfx_land', 'sfx_segment', 'sfx_hammer', 'music_win'].map((n) => entry(n, 22050)),
  ],
};
const file = join(ROOT, 'Assets', 'MinikUsta', 'Presentation.Core.Tests', 'Golden', 'audio_vectors.json');
writeFileSync(file, JSON.stringify(out) + '\n');
console.log(`audio vectors: ${out.sounds.length} sounds (${out.sounds.filter((s) => s.chaotic).length} with noise) -> ${file}`);
